SHEET_NAME = 'Справочник'


def _load_blocks_from_sheet():
    """Читает лист «Справочник» из той же Google Таблицы.
    Формат: колонка A — ключ блока, колонка C — текст. Пустой текст = блок отключён."""
    import streamlit as st

    @st.cache_data(ttl=600, show_spinner=False)
    def _cached():
        import os
        import gspread
        from utils.constants import DEFAULT_SHEET_ID
        scope = ['https://spreadsheets.google.com/feeds',
                 'https://www.googleapis.com/auth/drive']
        if "gcp_service_account" in st.secrets:
            from google.oauth2.service_account import Credentials
            credentials = Credentials.from_service_account_info(
                st.secrets["gcp_service_account"], scopes=scope)
        else:
            from oauth2client.service_account import ServiceAccountCredentials
            credentials_path = os.getenv('GOOGLE_APPLICATION_CREDENTIALS')
            if not credentials_path:
                base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
                for cand in (os.path.join(base, 'credentials.json'),
                             os.path.join(os.path.dirname(base), 'credentials.json')):
                    if os.path.exists(cand):
                        credentials_path = cand
                        break
            credentials = ServiceAccountCredentials.from_json_keyfile_name(credentials_path, scope)
        client = gspread.authorize(credentials)
        sheet_id = os.getenv('GOOGLE_SHEET_ID', DEFAULT_SHEET_ID)
        ws = client.open_by_key(sheet_id).worksheet(SHEET_NAME)
        rows = ws.get_all_values()
        blocks = {}
        for row in rows[1:]:
            if len(row) >= 3 and row[0].strip():
                blocks[row[0].strip()] = row[2].strip()
        return blocks

    return _cached()


def get_blocks():
    """Блоки справочника: из Google Таблицы, при недоступности — встроенные дефолты."""
    try:
        loaded = _load_blocks_from_sheet()
        if loaded:
            return {k: loaded.get(k, v) for k, v in DEFAULTS.items()}
    except Exception:
        pass
    return DEFAULTS


def select_knowledge(facts):
    """Подбор релевантных блоков справочника под текущие факты диагностики."""
    b = get_blocks()
    blocks = []
    if b.get('глоссарий'):
        blocks.append(b['глоссарий'])

    m = facts.get('машины', {})
    if (m.get('резко_ниже_партии_сейчас') or m.get('хронически_ниже_нормы_3_партии')) and b.get('машины_прочность'):
        blocks.append(b['машины_прочность'])

    spc = facts.get('SPC', {})
    cv_signal = spc.get('сигналы_CV') not in (None, 'нет')
    if (m.get('хронический_высокий_CV') or cv_signal or facts.get('текущая_партия', {}).get('выше_нормы_CV_шт', 0) > 5) and b.get('cv'):
        blocks.append(b['cv'])

    s_signal = spc.get('сигналы_прочность') not in (None, 'нет')
    if (facts.get('полимер', {}).get('подозрение') or s_signal) and b.get('полимер'):
        blocks.append(b['полимер'])

    vtv = facts.get('ВТВ')
    if isinstance(vtv, dict) and vtv.get('требуют_настройки_откл_за_5_партий') and b.get('втв'):
        blocks.append(b['втв'])

    return "\n\n".join(blocks)
